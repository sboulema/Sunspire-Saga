/**
 * Sprite packs: every image the engine loads (character and enemy sheets, spirits, tilesets,
 * backgrounds, icons, menu art) is a slot named after its file, and a pack replaces whole sheets
 * with the player's own PNG / GIF / WebP files of the same size, loaded one by one or as a zip;
 * a sheet may also bring its own `<slot>.json` frame atlas (same frame names, any layout) and
 * then be any size.
 * Accepted files live in the player's IndexedDB; at boot they become blob URLs that Phaser's
 * loader is pointed at instead of the files under assets/. The slot list, with sizes and frame
 * layouts, is static/pack-slots.json, generated by scripts/build_sunspire_assets.js.
 */

export type PackSlot = {
    /** The slot name: the asset file's name without extension. */
    slot: string;
    /** The asset path under the site root. */
    file: string;
    width: number;
    height: number;
    /** Frame names of an atlas, in the order they sit in the sheet; empty for a plain image. */
    frames: string[];
    /** Where the sheet is used, for the guide. */
    group: string;
};

export type PackReport = {
    loaded: string[];
    issues: string[];
    cleared?: boolean;
};

/** What the reload after an import or a clear should confirm. */
type PackNotice = {
    loaded: number;
    cleared?: boolean;
};

const NOTICE_KEY = "sunspire_pack_notice";
const DB_NAME = "sunspire_engine_packs";
const STORE = "sheets";
const MIME: {[ext: string]: string} = {
    png: "image/png",
    gif: "image/gif",
    webp: "image/webp",
    json: "application/json",
};
/** Store key suffix of a slot's own atlas. */
const ATLAS_SUFFIX = ".json";

export class SpritePacks {
    private static readonly SLOTS_URL = "static/pack-slots.json";

    /** Slot name -> slot description. */
    public slots: {[slot: string]: PackSlot} = {};
    /** Slot name -> blob URL of the pack's sheet. */
    private urls: {[slot: string]: string} = {};
    /** Slot name -> blob URL of the pack's own frame atlas for that sheet, when it brought one. */
    private atlas_urls: {[slot: string]: string} = {};
    private hooked: boolean = false;

    /**
     * Reads the slot list and the stored pack. Never throws: without IndexedDB or the slot list
     * the game simply runs with its own art.
     */
    static async open(): Promise<SpritePacks> {
        const packs = new SpritePacks();
        try {
            const list: PackSlot[] = await (await fetch(SpritePacks.SLOTS_URL)).json();
            list.forEach(slot => (packs.slots[slot.slot] = slot));
        } catch {
            console.warn("Sprite packs: the slot list could not be read; packs are off.");
            return packs;
        }
        try {
            const stored = await SpritePacks.store_all();
            for (const key in stored) {
                if (key.endsWith(ATLAS_SUFFIX)) {
                    const slot = key.slice(0, -ATLAS_SUFFIX.length);
                    if (slot in packs.slots) {
                        packs.atlas_urls[slot] = URL.createObjectURL(stored[key]);
                    }
                } else if (key in packs.slots) {
                    packs.urls[key] = URL.createObjectURL(stored[key]);
                }
            }
        } catch {
            // no IndexedDB: nothing to restore
        }
        return packs;
    }

    /** Slot names the active pack covers. */
    get covered(): string[] {
        return Object.keys(this.urls);
    }

    /**
     * Points Phaser's loader at the pack's sheets: every image, atlas image and bitmap font page
     * whose file name is a covered slot loads from the pack instead. Call once, before the game
     * is created.
     */
    hook_loader() {
        if (this.hooked) {
            return;
        }
        this.hooked = true;
        const packs = this;
        const original = Phaser.Loader.prototype.addToFileList;
        Phaser.Loader.prototype.addToFileList = function (type, key, url, properties, overwrite, extension) {
            if (typeof url === "string" && (type === "image" || type === "textureatlas" || type === "bitmapfont")) {
                const replacement = packs.urls[SpritePacks.slot_of(url)];
                if (replacement) {
                    url = replacement;
                }
            }
            if (type === "textureatlas" && properties && typeof properties.atlasURL === "string") {
                const atlas = packs.atlas_urls[SpritePacks.slot_of(properties.atlasURL)];
                if (atlas) {
                    properties = {...properties, atlasURL: atlas};
                }
            }
            return original.call(this, type, key, url, properties, overwrite, extension);
        };
    }

    /** The slot an asset URL belongs to: its file name without the extension. */
    private static slot_of(url: string) {
        return url
            .split("/")
            .pop()
            .replace(/\.[^.]*$/, "");
    }

    /**
     * Imports pack files (images, atlases or zips): each must be named after a slot. A sheet alone
     * must have the built-in sheet's exact size, since the game cuts it with the built-in frame
     * layout; a sheet that comes with its own `<slot>.json` TexturePacker atlas (same frame names,
     * any positions and sizes) may be any size that holds those frames. Accepted files are stored
     * and take effect on the next load of the page.
     */
    async import_files(files: File[]): Promise<PackReport> {
        const report: PackReport = {loaded: [], issues: []};
        const images: File[] = [],
            atlases: File[] = [];
        const sort = (file: File) => (/\.json$/i.test(file.name) ? atlases : images).push(file);
        for (const file of files) {
            if (/\.zip$/i.test(file.name)) {
                try {
                    const got = await SpritePacks.extract_zip(file);
                    if (!got.length) {
                        report.issues.push(`${file.name}: the zip holds no PNG, GIF or WebP files`);
                    }
                    got.forEach(sort);
                } catch {
                    report.issues.push(`${file.name}: not a readable zip`);
                }
            } else {
                sort(file);
            }
        }
        // atlases first: they decide what size their sheet may have
        const extents: {[slot: string]: {width: number; height: number}} = {};
        for (const file of atlases) {
            const slot = SpritePacks.slot_of(file.name);
            const def = this.slots[slot];
            if (!def) {
                report.issues.push(`${file.name}: no slot with this name (see the pack guide)`);
                continue;
            }
            if (!def.frames.length) {
                report.issues.push(`${file.name}: ${slot} is a plain image, it takes no frame atlas`);
                continue;
            }
            if (!images.some(image => SpritePacks.slot_of(image.name) === slot)) {
                report.issues.push(`${file.name}: an atlas needs its ${slot} sheet in the same pack`);
                continue;
            }
            let extent: {width: number; height: number};
            try {
                extent = SpritePacks.check_atlas(JSON.parse(await file.text()), def);
            } catch (e) {
                report.issues.push(`${file.name}: ${e instanceof Error ? e.message : "not a readable atlas"}`);
                continue;
            }
            try {
                await SpritePacks.store_put(slot + ATLAS_SUFFIX, file);
            } catch {
                report.issues.push(`${file.name}: this browser has no storage for packs; nothing was saved`);
                continue;
            }
            if (this.atlas_urls[slot]) {
                URL.revokeObjectURL(this.atlas_urls[slot]);
            }
            this.atlas_urls[slot] = URL.createObjectURL(file);
            extents[slot] = extent;
        }
        for (const file of images) {
            const slot = SpritePacks.slot_of(file.name);
            const def = this.slots[slot];
            if (!def) {
                report.issues.push(`${file.name}: no slot with this name (see the pack guide)`);
                continue;
            }
            const size = await SpritePacks.image_size(file);
            if (!size) {
                report.issues.push(`${file.name}: could not be read as an image`);
                continue;
            }
            const extent = extents[slot];
            if (extent) {
                if (size.width < extent.width || size.height < extent.height) {
                    report.issues.push(
                        `${file.name}: is ${size.width}x${size.height}, its atlas needs at least ${extent.width}x${extent.height}`
                    );
                    continue;
                }
            } else {
                if (size.width !== def.width || size.height !== def.height) {
                    report.issues.push(
                        `${file.name}: is ${size.width}x${size.height}, the ${slot} sheet is ${def.width}x${def.height} (or add a ${slot}.json atlas for another size)`
                    );
                    continue;
                }
                if (this.atlas_urls[slot]) {
                    // a sheet without its own atlas goes back to the built-in frame layout
                    URL.revokeObjectURL(this.atlas_urls[slot]);
                    delete this.atlas_urls[slot];
                    try {
                        await SpritePacks.store_delete(slot + ATLAS_SUFFIX);
                    } catch {
                        // nothing stored
                    }
                }
            }
            try {
                await SpritePacks.store_put(slot, file);
            } catch {
                report.issues.push(`${file.name}: this browser has no storage for packs; nothing was saved`);
                continue;
            }
            if (this.urls[slot]) {
                URL.revokeObjectURL(this.urls[slot]);
            }
            this.urls[slot] = URL.createObjectURL(file);
            report.loaded.push(slot);
        }
        return report;
    }

    /** Drops the stored pack; the built-in art is back on the next load of the page. */
    async clear(): Promise<PackReport> {
        for (const slot in this.urls) {
            URL.revokeObjectURL(this.urls[slot]);
        }
        for (const slot in this.atlas_urls) {
            URL.revokeObjectURL(this.atlas_urls[slot]);
        }
        this.urls = {};
        this.atlas_urls = {};
        try {
            await SpritePacks.store_clear();
        } catch {
            // nothing stored
        }
        return {loaded: [], issues: [], cleared: true};
    }

    /**
     * Wires the pack file input, status line and clear button of the page, when present. A pack
     * only takes effect when the page loads, so a successful import (or a clear) reloads the page
     * and the confirmation is shown after the reload.
     */
    bind_page() {
        const input = document.getElementById("packIn") as HTMLInputElement;
        const status = document.getElementById("packStatus");
        const clear = document.getElementById("packClear");
        if (!input || !status) {
            return;
        }
        const sheets = (n: number) => `${n} sheet${n === 1 ? "" : "s"}`;
        const reload = (notice: PackNotice) => {
            try {
                sessionStorage.setItem(NOTICE_KEY, JSON.stringify(notice));
            } catch {
                // the confirmation is just lost
            }
            location.reload();
        };
        const show = (report: PackReport) => {
            if (!report.issues.length && (report.cleared || report.loaded.length)) {
                reload({loaded: report.loaded.length, cleared: report.cleared});
                return;
            }
            const lines: string[] = report.issues.map(
                issue => `<span class="warn">${SpritePacks.escape(issue)}</span>`
            );
            if (report.loaded.length) {
                lines.push(
                    `<span class="ok">${sheets(report.loaded.length)} loaded.</span> Reload the page to see them.`
                );
            }
            status.innerHTML = lines.join("<br>");
        };
        input.addEventListener("change", async () => {
            const report = await this.import_files(Array.from(input.files));
            show(report);
            input.value = "";
        });
        clear?.addEventListener("click", async () => show(await this.clear()));

        const notice = SpritePacks.take_notice();
        if (notice?.cleared) {
            status.innerHTML = `<span class="ok">Pack cleared: the built-in art is back.</span>`;
        } else if (notice?.loaded) {
            status.innerHTML = `<span class="ok">Sprite pack loaded: ${sheets(notice.loaded)} replaced.</span>`;
        } else if (this.covered.length) {
            status.innerHTML = `<span class="ok">Pack active: ${sheets(this.covered.length)} replaced.</span>`;
        }
    }

    /** The confirmation left by the import or clear that reloaded the page, if any. */
    private static take_notice(): PackNotice | null {
        try {
            const raw = sessionStorage.getItem(NOTICE_KEY);
            sessionStorage.removeItem(NOTICE_KEY);
            return raw ? JSON.parse(raw) : null;
        } catch {
            return null;
        }
    }

    /**
     * Checks a pack's atlas against the built-in sheet it replaces: a TexturePacker JSON (hash or
     * array) with exactly the frame names the game animates. Returns the size the sheet must have.
     */
    private static check_atlas(json: any, def: PackSlot): {width: number; height: number} {
        const frames = json && json.frames;
        if (!frames || typeof frames !== "object") {
            throw new Error("not a TexturePacker atlas (no frames)");
        }
        const entries: [string, any][] = Array.isArray(frames)
            ? frames.map(f => [f && f.filename, f] as [string, any])
            : Object.entries(frames);
        const names = new Set(entries.map(e => e[0]));
        const wanted = new Set(def.frames);
        const missing = def.frames.filter(n => !names.has(n));
        const unknown = [...names].filter(n => !wanted.has(n));
        if (missing.length || unknown.length) {
            const what = [
                missing.length ? `${missing.length} missing (${missing.slice(0, 3).join(", ")}…)` : "",
                unknown.length ? `${unknown.length} unknown` : "",
            ]
                .filter(Boolean)
                .join(", ");
            throw new Error(
                `its frame names differ from the ${def.slot} sheet: ${what}; the game needs exactly those frames`
            );
        }
        let width = 0,
            height = 0;
        for (const [name, f] of entries) {
            const r = f && f.frame;
            if (!r || [r.x, r.y, r.w, r.h].some(v => typeof v !== "number" || v < 0)) {
                throw new Error(`frame ${name} has no usable rectangle`);
            }
            width = Math.max(width, r.x + r.w);
            height = Math.max(height, r.y + r.h);
        }
        return {width, height};
    }

    private static escape(text: string) {
        return text.replace(/[&<>]/g, c => ({"&": "&amp;", "<": "&lt;", ">": "&gt;"})[c]);
    }

    private static image_size(file: Blob): Promise<{width: number; height: number} | null> {
        return new Promise(resolve => {
            const url = URL.createObjectURL(file);
            const img = new Image();
            img.onload = () => {
                URL.revokeObjectURL(url);
                resolve({width: img.naturalWidth, height: img.naturalHeight});
            };
            img.onerror = () => {
                URL.revokeObjectURL(url);
                resolve(null);
            };
            img.src = url;
        });
    }

    // ---------------- zip ----------------
    /** The PNG, GIF and WebP files inside a zip, whatever folders they sit in (stored or deflated). */
    private static async extract_zip(file: File): Promise<File[]> {
        const buf = new Uint8Array(await file.arrayBuffer());
        const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
        let eocd = -1;
        for (let i = buf.length - 22; i >= Math.max(0, buf.length - 65558); i--) {
            if (dv.getUint32(i, true) === 0x06054b50) {
                eocd = i;
                break;
            }
        }
        if (eocd < 0) {
            throw new Error("not a zip");
        }
        const count = dv.getUint16(eocd + 10, true);
        let p = dv.getUint32(eocd + 16, true);
        const out: File[] = [];
        for (let i = 0; i < count; i++) {
            if (dv.getUint32(p, true) !== 0x02014b50) {
                break;
            }
            const method = dv.getUint16(p + 10, true);
            const csize = dv.getUint32(p + 20, true);
            const nlen = dv.getUint16(p + 28, true);
            const xlen = dv.getUint16(p + 30, true);
            const clen = dv.getUint16(p + 32, true);
            const lho = dv.getUint32(p + 42, true);
            const name = new TextDecoder().decode(buf.subarray(p + 46, p + 46 + nlen));
            p += 46 + nlen + xlen + clen;
            if (name.endsWith("/")) {
                continue;
            }
            const base = name.split("/").pop().split("\\").pop();
            const ext = (base.indexOf(".") >= 0 ? base.split(".").pop() : "").toLowerCase();
            if (!MIME[ext]) {
                continue;
            }
            const lnlen = dv.getUint16(lho + 26, true);
            const lxlen = dv.getUint16(lho + 28, true);
            const start = lho + 30 + lnlen + lxlen;
            let bytes: Uint8Array = buf.subarray(start, start + csize);
            if (method === 8) {
                if (!(window as any).DecompressionStream) {
                    continue;
                }
                const ds = new (window as any).DecompressionStream("deflate-raw");
                const ab = await new Response(new Blob([bytes as any]).stream().pipeThrough(ds)).arrayBuffer();
                bytes = new Uint8Array(ab);
            } else if (method !== 0) {
                continue;
            }
            out.push(new File([bytes as any], base, {type: MIME[ext]}));
        }
        return out;
    }

    // ---------------- IndexedDB ----------------
    private static open_db(): Promise<IDBDatabase | null> {
        return new Promise(resolve => {
            if (!window.indexedDB) {
                return resolve(null);
            }
            try {
                const request = indexedDB.open(DB_NAME, 1);
                request.onupgradeneeded = () => request.result.createObjectStore(STORE);
                request.onsuccess = () => resolve(request.result);
                request.onerror = () => resolve(null);
                request.onblocked = () => resolve(null);
            } catch {
                resolve(null);
            }
        });
    }

    private static transaction(db: IDBDatabase, mode: IDBTransactionMode, fn: (store: IDBObjectStore) => void) {
        return new Promise<void>((resolve, reject) => {
            const tx = db.transaction(STORE, mode);
            try {
                fn(tx.objectStore(STORE));
            } catch (e) {
                reject(e);
                return;
            }
            tx.oncomplete = () => resolve();
            tx.onerror = () => reject(tx.error);
            tx.onabort = () => reject(tx.error || new Error("aborted"));
        });
    }

    /** Every stored sheet, slot -> blob. */
    static async store_all(): Promise<{[slot: string]: Blob}> {
        const db = await SpritePacks.open_db();
        if (!db) {
            throw new Error("no IndexedDB");
        }
        const out: {[slot: string]: Blob} = {};
        await new Promise<void>(resolve => {
            const request = db.transaction(STORE, "readonly").objectStore(STORE).openCursor();
            request.onsuccess = () => {
                const cursor = request.result;
                if (cursor) {
                    out[cursor.key as string] = cursor.value;
                    cursor.continue();
                } else {
                    resolve();
                }
            };
            request.onerror = () => resolve();
        });
        return out;
    }

    private static async store_put(slot: string, blob: Blob) {
        const db = await SpritePacks.open_db();
        if (!db) {
            throw new Error("no IndexedDB");
        }
        await SpritePacks.transaction(db, "readwrite", store => store.put(blob, slot));
    }

    private static async store_delete(key: string) {
        const db = await SpritePacks.open_db();
        if (db) {
            await SpritePacks.transaction(db, "readwrite", store => store.delete(key));
        }
    }

    private static async store_clear() {
        const db = await SpritePacks.open_db();
        if (db) {
            await SpritePacks.transaction(db, "readwrite", store => store.clear());
        }
    }
}
