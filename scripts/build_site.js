// Assembles the static site in site/: the page, the production bundle, the game assets and the
// static files, ready for any web root (GitHub Pages, a Docker image, a zip).
//
//   npm run site      (runs build_prod first)
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "site");

fs.rmSync(OUT, {recursive: true, force: true});
fs.mkdirSync(OUT, {recursive: true});
for (const entry of ["index.html", "pack-guide.html", "walkthrough.html", "dist/bundle.js", "assets", "static", "LICENSE.txt"]) {
    const src = path.join(ROOT, entry);
    if (!fs.existsSync(src)) throw new Error(`missing ${entry}; run npm run build_prod first`);
    fs.cpSync(src, path.join(OUT, entry), {recursive: true});
}
// the source art and tile grid are inputs of scripts/build_sunspire_assets.js, not game files
fs.rmSync(path.join(OUT, "assets/sunspire"), {recursive: true, force: true});
// production mode: no debug overlay redraw per frame, no debug hotkeys
const init_path = path.join(OUT, "assets/init.json");
const init = JSON.parse(fs.readFileSync(init_path, "utf8"));
init.production_mode = true;
fs.writeFileSync(init_path, JSON.stringify(init, null, 4) + "\n");
fs.writeFileSync(path.join(OUT, ".nojekyll"), "");

// the service worker: every file of the site is precached on install, so the installed app plays
// offline; pages, the bundle and game data come from the network first (a new release shows on
// the next launch), art, sounds and fonts from the cache first. The cache is named after the
// content, so a new build replaces the old cache on activation.
const files = [];
const walk = dir => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
        const file = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(file);
        else files.push("/" + path.relative(OUT, file).replace(/\\/g, "/"));
    }
};
walk(OUT);
const hash = require("crypto").createHash("sha1");
for (const file of files.sort()) hash.update(file + fs.statSync(path.join(OUT, file)).size);
const version = hash.digest("hex").slice(0, 12);
const precache = files.filter(f => !/\.(nojekyll)$/.test(f) && !f.startsWith("/assets/sunspire/")).concat(["/"]);
fs.writeFileSync(path.join(OUT, "sw.js"), `// Sunspire Saga service worker, generated by scripts/build_site.js. Do not edit.
const CACHE = "sunspire-${version}";
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener("install", e => {
    e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
    e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
    const req = e.request;
    if (req.method !== "GET") return;
    const url = new URL(req.url);
    const fonts = url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com";
    if (url.origin !== location.origin && !fonts) return;
    const media = fonts || /\\.(png|jpg|gif|webp|wav|ogg|fnt|ico|woff2?)$/.test(url.pathname);
    e.respondWith(media ? fromCache(req) : fromNetwork(req));
});
async function fromNetwork(req) {
    const c = await caches.open(CACHE);
    try {
        const res = await fetch(req);
        if (res.ok && !res.redirected) c.put(req, res.clone());
        return res;
    } catch (err) {
        // the app's start URL carries ?app=1; the cached page is the same without it
        const hit = await c.match(req, {ignoreSearch: true});
        if (hit) return hit;
        if (req.mode === "navigate") { const page = await c.match("/"); if (page) return page; }
        throw err;
    }
}
async function fromCache(req) {
    const c = await caches.open(CACHE);
    const hit = await c.match(req);
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok || res.type === "opaque") c.put(req, res.clone());
    return res;
}
`);
console.log(`site/ ready: ${files.length} files, service worker cache sunspire-${version}`);
